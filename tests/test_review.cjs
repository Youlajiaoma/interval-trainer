const fs=require('fs'), assert=require('assert/strict'),vm=require('vm'),path=require('path');
const code=fs.readFileSync(path.join(__dirname,'../site/review.js'),'utf8');
const context={window:{},Date,Math,JSON};vm.runInNewContext(code,context);
const api=context.window.IntervalReview;
const map=new Map();const storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
const r=api.createReviewManager(storage);
const day1=new Date(2026,9,12,10,0).getTime();
const day2=new Date(2026,9,13,9,0).getTime();
assert.equal(r.analysis([3,4,7],day1).total,0);
r.record({actual:4,chosen:3,low:60,high:64,now:day1,responseMs:1600});
assert.equal(r.analysis([4],day1).yesterdayWrong.length,0);
assert.equal(r.analysis([4],day2).yesterdayWrong[0].semi,4);
assert.equal(r.snapshot().cards[4].dueAt,api.addCalendarDays(day1,1));
assert.equal(r.choose([3,4,7],null,{now:day2,random:()=>0}),4,'新一天首次优先昨日错题');
assert.equal(r.choose([3,4,7],4,{now:day2,random:()=>0}),3,'不连续相同音程');
assert.equal(r.statistics(30,day2).totals.answered,1);
assert.equal(r.statistics(30,day2).byInterval[4].correct,0);
assert.equal(r.statistics(30,day2).totals.responseCount,1);
r.record({actual:3,chosen:3,now:day2,low:61,high:64,hinted:true,responseMs:2400});
r.skip({now:day2});
assert.equal(r.statistics(30,day2).totals.skipped,1);
assert.equal(r.statistics(30,day2).totals.hints,1);
assert.equal(r.statistics(30,day2).totals.responseTotal,4000);
const r2=api.createReviewManager(storage);
assert.equal(r2.analysis([3,4],day2).total,2);
assert.equal(r2.statistics(30,day2).practiceDays,2);
const backup=r2.exportJson();
assert.equal(JSON.parse(backup).daily['2026-10-12'].intervals[4].correct,0);
assert.equal(r2.statistics(7,day2).trend.length,7);
assert.equal(r2.statistics(30,day2).trend.length,30);
assert.equal(r2.statistics(90,day2).trend.length,90);
const r3=api.createReviewManager(storage);r3.reset();assert.equal(r3.statistics(30,day2).totals.answered,0);
r3.importJson(backup);assert.equal(r3.statistics(30,day2).totals.answered,2);
assert.throws(()=>r3.importJson('{"version":999}'));
assert.equal(r3.statistics(30,day2).totals.answered,2);
// v1.3 数据可迁移：无 daily 字段时，使用历史来填充逐日统计。
const old=JSON.parse(backup);delete old.daily;const migrated=api.normalizeStore(old);
assert.equal(migrated.daily['2026-10-12'].answered,1);
assert.equal(migrated.daily['2026-10-13'].answered,1);
// 正确答案不会让昨日错题被当作一个新题目类型；针对复习每次仍由抽题器生成不同根音。
assert.equal(r3.analysis([4],day2).due.length,1);
console.log('PASS: previous-day focus, weighted review, daily stats, response time, skip, backup, migration');
